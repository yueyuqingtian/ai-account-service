CREATE TABLE IF NOT EXISTS sys_user (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(64) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  email VARCHAR(128),
  status VARCHAR(32) NOT NULL DEFAULT 'ENABLED',
  register_ip VARCHAR(64),
  last_login_at TIMESTAMP,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sys_admin (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(64) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role_code VARCHAR(64) NOT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'ENABLED',
  last_login_at TIMESTAMP,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS product (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_code VARCHAR(64) NOT NULL UNIQUE,
  name VARCHAR(128) NOT NULL,
  subtitle VARCHAR(255),
  cover_url VARCHAR(512),
  price DECIMAL(10,2) NOT NULL,
  original_price DECIMAL(10,2),
  delivery_type VARCHAR(32) NOT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'OFF_SHELF',
  description CLOB,
  stock_display_mode VARCHAR(32) NOT NULL DEFAULT 'HIDE',
  sort INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS order_info (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_no VARCHAR(64) NOT NULL UNIQUE,
  user_id BIGINT NOT NULL,
  product_id BIGINT NOT NULL,
  product_name_snapshot VARCHAR(128) NOT NULL,
  price_snapshot DECIMAL(10,2) NOT NULL,
  quantity INT NOT NULL DEFAULT 1,
  amount DECIMAL(10,2) NOT NULL,
  pay_amount DECIMAL(10,2) NOT NULL,
  order_status VARCHAR(32) NOT NULL DEFAULT 'UNPAID',
  pay_status VARCHAR(32) NOT NULL DEFAULT 'UNPAID',
  delivery_status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
  client_type VARCHAR(32) NOT NULL DEFAULT 'WEB',
  closed_reason VARCHAR(255),
  paid_at TIMESTAMP,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS payment_record (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_no VARCHAR(64) NOT NULL UNIQUE,
  order_no VARCHAR(64) NOT NULL,
  channel VARCHAR(32) NOT NULL,
  amount DECIMAL(10,2) NOT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'INIT',
  third_party_trade_no VARCHAR(128),
  callback_raw CLOB,
  paid_at TIMESTAMP,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS cdk_record (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cdk_code VARCHAR(64) NOT NULL UNIQUE,
  product_id BIGINT NOT NULL,
  order_id BIGINT,
  order_no VARCHAR(64),
  owner_user_id BIGINT,
  status VARCHAR(32) NOT NULL DEFAULT 'UNBOUND',
  expired_at TIMESTAMP,
  used_at TIMESTAMP,
  used_by_user_id BIGINT,
  delivery_snapshot CLOB,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS inventory_account (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_no VARCHAR(64) NOT NULL,
  product_id BIGINT NOT NULL,
  resource_account VARCHAR(255) NOT NULL,
  resource_password_cipher VARCHAR(512) NOT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'AVAILABLE',
  assigned_order_no VARCHAR(64),
  assigned_user_id BIGINT,
  assigned_at TIMESTAMP,
  remark VARCHAR(500),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(product_id, resource_account)
);

CREATE TABLE IF NOT EXISTS redeem_record (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  redeem_no VARCHAR(64) NOT NULL UNIQUE,
  user_id BIGINT NOT NULL,
  cdk_id BIGINT,
  cdk_code VARCHAR(64) NOT NULL,
  product_id BIGINT,
  inventory_id BIGINT,
  result VARCHAR(32) NOT NULL,
  fail_reason VARCHAR(255),
  client_ip VARCHAR(64),
  device_fingerprint VARCHAR(255),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS admin_operation_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_id BIGINT NOT NULL,
  module VARCHAR(64) NOT NULL,
  operation_type VARCHAR(64) NOT NULL,
  target_id VARCHAR(64),
  before_json CLOB,
  after_json CLOB,
  client_ip VARCHAR(64),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS system_config (
  config_key VARCHAR(128) PRIMARY KEY,
  config_value CLOB,
  encrypted BOOLEAN NOT NULL DEFAULT FALSE,
  remark VARCHAR(255),
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS verification_code_query_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  resource_account VARCHAR(255) NOT NULL,
  result VARCHAR(32) NOT NULL,
  code_value VARCHAR(16),
  message_subject VARCHAR(500),
  fail_reason VARCHAR(255),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS email_verification_code (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(128) NOT NULL,
  code_value VARCHAR(16) NOT NULL,
  scene VARCHAR(32) NOT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'UNUSED',
  expired_at TIMESTAMP NOT NULL,
  used_at TIMESTAMP,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
